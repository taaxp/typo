#if os(macOS)
import AppKit
import SwiftData
import Observation
import UniformTypeIdentifiers

/// One clipboard entry. Stored in a separate, local-only store that never syncs.
@Model
final class HistoryEntry {
    var uuid: UUID = UUID()
    var text: String = ""
    var typeIdentifier: String?
    @Attribute(.externalStorage) var data: Data?
    var sourceApp: String = ""
    var copiedAt: Date = Date()

    init(text: String, typeIdentifier: String? = nil, data: Data? = nil, sourceApp: String) {
        self.text = text
        self.typeIdentifier = typeIdentifier
        self.data = data
        self.sourceApp = sourceApp
    }

    var isImage: Bool { typeIdentifier.flatMap(UTType.init)?.conforms(to: .image) == true }
}

/// Mac clipboard history. **Off by default.**
///
/// - Polls `NSPasteboard.general.changeCount` twice a second (macOS has no
///   clipboard-change notification).
/// - Skips anything marked concealed, transient or auto-generated (the
///   nspasteboard.org convention used by password managers), and Typo's own
///   sensitive copies.
/// - Keeps 200 entries or 7 days, on this Mac only.
@MainActor
@Observable
final class ClipboardHistory {
    static let enabledKey = "mac.historyEnabled"
    static let maxEntries = 200
    static let maxAge: TimeInterval = 7 * 24 * 3600
    static let maxDataBytes = 10 * 1024 * 1024

    let container: ModelContainer
    private(set) var isRunning = false
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount

    private static let skipTypes: [NSPasteboard.PasteboardType] = [
        Clipboard.concealedType, Clipboard.transientType,
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    init() {
        let url = AppGroup.containerURL.appendingPathComponent("ClipboardHistory.store")
        let config = ModelConfiguration("ClipboardHistory", schema: Schema([HistoryEntry.self]), url: url, cloudKitDatabase: .none)
        container = (try? ModelContainer(for: HistoryEntry.self, configurations: config))
            ?? (try! ModelContainer(for: HistoryEntry.self, configurations: ModelConfiguration(isStoredInMemoryOnly: true)))
    }

    var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: Self.enabledKey) }
        set {
            UserDefaults.standard.set(newValue, forKey: Self.enabledKey)
            newValue ? start() : stop()
        }
    }

    func start() {
        guard isEnabled, timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        isRunning = true
        prune()
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        isRunning = false
    }

    func clear() {
        try? container.mainContext.delete(model: HistoryEntry.self)
        try? container.mainContext.save()
    }

    func recent(limit: Int = 50) -> [HistoryEntry] {
        var d = FetchDescriptor<HistoryEntry>(sortBy: [SortDescriptor(\.copiedAt, order: .reverse)])
        d.fetchLimit = limit
        return (try? container.mainContext.fetch(d)) ?? []
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = pb.types ?? []
        if types.contains(where: Self.skipTypes.contains) { return }
        // Ignore copies made by Typo itself.
        if NSWorkspace.shared.frontmostApplication?.bundleIdentifier == Bundle.main.bundleIdentifier { return }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName ?? ""

        let entry: HistoryEntry
        if let string = pb.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            if recent(limit: 1).first?.text == string { return }
            entry = HistoryEntry(text: string, sourceApp: source)
        } else if let png = pb.data(forType: .png) ?? pb.data(forType: .tiff).flatMap({ NSBitmapImageRep(data: $0)?.representation(using: .png, properties: [:]) }),
                  png.count <= Self.maxDataBytes {
            entry = HistoryEntry(text: "Image", typeIdentifier: UTType.png.identifier, data: png, sourceApp: source)
        } else {
            return
        }
        container.mainContext.insert(entry)
        try? container.mainContext.save()
        prune()
    }

    private func prune() {
        let cutoff = Date().addingTimeInterval(-Self.maxAge)
        try? container.mainContext.delete(model: HistoryEntry.self, where: #Predicate { $0.copiedAt < cutoff })
        let all = (try? container.mainContext.fetch(FetchDescriptor<HistoryEntry>(sortBy: [SortDescriptor(\.copiedAt, order: .reverse)]))) ?? []
        all.dropFirst(Self.maxEntries).forEach(container.mainContext.delete)
        try? container.mainContext.save()
    }

    func copy(_ entry: HistoryEntry) {
        if let data = entry.data, let type = entry.typeIdentifier {
            NSPasteboard.general.clearContents()
            NSPasteboard.general.setData(data, forType: NSPasteboard.PasteboardType(type))
        } else {
            Clipboard.copy(text: entry.text)
        }
        lastChange = NSPasteboard.general.changeCount   // don't record our own copy
    }

    /// Call after Typo itself writes to the clipboard, so the copy isn't recorded.
    func ignoreCurrentChange() { lastChange = NSPasteboard.general.changeCount }

    /// Promotes a history entry into the synced Typo library.
    func saveToTypo(_ entry: HistoryEntry, context: ModelContext) {
        let library = TypoLibrary(context: context)
        if let data = entry.data, let type = entry.typeIdentifier.flatMap(UTType.init),
           let draft = try? Ingest.draft(fromData: data, type: type, filename: nil) {
            library.save(draft)
        } else if let draft = Ingest.draft(fromText: entry.text) {
            library.save(draft)
        }
    }
}
#endif
